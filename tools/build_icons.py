"""Build icons.css: the Font Awesome icons this site uses, as CSS masks.

The page keeps Font Awesome's markup (<i class="fas fa-github">), so HTML and JS stay the same,
but nothing is downloaded from a CDN: each icon is an inline SVG used as a mask, painted with
the element's text colour (or with its gradient background, where the CSS sets one).

Usage:
    npm pack @fortawesome/fontawesome-free@6.5.1 && tar -xzf fortawesome-fontawesome-free-6.5.1.tgz
    python tools/build_icons.py package/svgs
"""

import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent

# Old Font Awesome 5 class names used on the site -> Font Awesome 6 file names.
ALIASES = {
    "times": "xmark",
    "search": "magnifying-glass",
    "search-plus": "magnifying-glass-plus",
    "undo": "rotate-left",
    "map-marker-alt": "location-dot",
    "play-circle": "circle-play",
    "coffee": "mug-saucer",
}


def used_icons() -> list[tuple[str, str]]:
    text = (ROOT / "index.html").read_text() + (ROOT / "script.js").read_text()
    found = set(re.findall(r"\b(fa[sb])\s+fa-([a-z0-9-]+)", text))
    # Icons that JavaScript swaps in by class name only.
    found |= {("fas", "bars"), ("fas", "times"), ("fas", "sun"), ("fas", "moon")}
    return sorted(found, key=lambda p: p[1])


def main(svg_root: str) -> None:
    root = Path(svg_root)
    rules = []
    for style, name in used_icons():
        folder = "brands" if style == "fab" else "solid"
        path = root / folder / f"{ALIASES.get(name, name)}.svg"
        svg = path.read_text()
        svg = re.sub(r"<!--.*?-->", "", svg).strip()
        rules.append(f'.fa-{name}{{--fa:url("data:image/svg+xml,{quote(svg, safe=" /=:")}")}}')

    css = (
        "/* Generated by tools/build_icons.py from Font Awesome Free 6.5.1 (CC BY 4.0 icons). Do not edit. */\n"
        "i.fas,i.fab{display:inline-block;width:1em;height:1em;vertical-align:-.125em;flex-shrink:0;"
        "background-color:currentColor;-webkit-mask:var(--fa) center/contain no-repeat;mask:var(--fa) center/contain no-repeat;"
        "-webkit-background-clip:border-box!important;background-clip:border-box!important;-webkit-text-fill-color:initial!important}\n"
        + "\n".join(rules)
        + "\n"
    )
    (ROOT / "icons.css").write_text(css)
    print(f"icons.css: {len(rules)} icons, {len(css) / 1024:.1f} KB")


if __name__ == "__main__":
    main(sys.argv[1])
